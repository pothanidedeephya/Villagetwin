export function getFallbackImdDistrictAreas(): FallbackDistrictArea[] {
  return DISTRICT_NAMES.map((name, index) => {
    // Coastal AP / East coast gets Yellow Watch during low-pressure watch
    const isCoastalWatch = ['KRISHNA', 'SRIKAKULAM', 'BAPATLA', 'GUNTUR', 'PRAKASAM', 'EAST GODAVARI', 'WEST GODAVARI'].includes(name);
    return {
      id: `dist-${index + 1}`,
      title: name,
      color: isCoastalWatch ? '#FFFF00' : '#7CFC00',
      balloonText: isCoastalWatch
        ? `<b>${name}</b><br/>Yellow Watch: Squally winds and localized rainfall watch under developing Bay of Bengal low-pressure system.`
        : `<b>${name}</b><br/>Green: No severe weather warning in effect. Normal seasonal weather.`,
    };
  });
}

