/**
 * Resolve an Indian PIN code into an authoritative LocationSearchResult
 */
export function resolvePincodeToLocation(pincodeQuery: string): LocationSearchResult | null {
  const clean = pincodeQuery.trim();
  if (!/^\d{6}$/.test(clean)) return null;

  const match = NATIONWIDE_PINCODE_INDEX[clean];
  if (match) {
    const [lng, lat] = match.center;
    return {
      id: `pin-${match.pincode}`,
      name: `${match.locality} (${match.pincode})`,
      displayName: `${match.pincode} — ${match.locality}, ${match.subdistrict}, ${match.district} District, ${match.state}`,
      adminLevel: 'village',
      state: match.state,
      district: match.district,
      subdistrict: match.subdistrict,
      center: [lng, lat],
      boundingBox: [lng - 0.025, lat - 0.025, lng + 0.025, lat + 0.025],
      elevation_m: match.elevation_m,
      population: 4500,
      source: 'Department of Posts, Ministry of Communications, GoI (data.gov.in)',
      regionCategory: match.regionCategory,
    };
  }

  return null;
}
